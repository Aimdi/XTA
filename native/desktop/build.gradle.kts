val versionName = System.getenv("NATIVE_VERSION_NAME") ?: "0.1.0"
// A build CI numbered is that prerelease, which the update check compares by (ui/chrome/Updates.kt); a local build has none.
val releaseTag = System.getenv("NATIVE_VERSION_NAME")?.takeIf { it.isNotBlank() }?.let { "native-$it" }.orEmpty()

// The SHA-256 of the certificate every plugin JAR must be signed by, built
// into the app (PLUGINS.md): the signing key's (see the root build file), or
// -PpluginCertSha256=<hex> when given.
@Suppress("UNCHECKED_CAST")
val signing = rootProject.extra["signing"] as Map<String, String>
val givenCertificate = (findProperty("pluginCertSha256") as String?)?.replace(":", "")?.trim()?.lowercase().orEmpty()
val pluginCertificate by tasks.registering {
    dependsOn(":signingKey")
    val out = layout.buildDirectory.dir("generated/plugin-certificate/kotlin")
    outputs.dir(out)
    // A few bytes, written each build: the key may change while the build files do not.
    outputs.upToDateWhen { false }
    doLast {
        val sha256 = givenCertificate.ifEmpty { certificateSha256(signing) }
        check(Regex("^[0-9a-f]{64}$").matches(sha256)) { "a SHA-256 fingerprint is 64 hex digits: $sha256" }
        val from = if (givenCertificate.isNotEmpty()) "-PpluginCertSha256" else signing.getValue("kind")
        val file = out.get().file("com/aimdi/xtanative/desktop/PluginCertificate.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |package com.aimdi.xtanative.desktop
            |
            |/** The SHA-256 of the certificate plugin JARs must be signed by: $from. Generated by the build. */
            |internal const val PLUGIN_CERTIFICATE_SHA256 = "$sha256"
            |
            """.trimMargin(),
        )
        logger.lifecycle("Desktop plugins must be signed by the certificate with SHA-256 $sha256 ($from)")
    }
}
kotlin.sourceSets["main"].kotlin.srcDir(pluginCertificate)

// Settings › App info › Licences: what the app ships, with the licences (gradle/licences.gradle.kts).
apply(from = rootProject.file("gradle/licences.gradle.kts"))
@Suppress("UNCHECKED_CAST")
val writeLicences = extra["writeLicences"] as (String, File) -> Unit
val appLicences by tasks.registering {
    val out = layout.buildDirectory.dir("generated/licences")
    outputs.dir(out)
    // The libraries are Gradle's to resolve each build; listing them is quick.
    outputs.upToDateWhen { false }
    doLast {
        val folder = out.get().asFile
        folder.deleteRecursively()
        writeLicences("runtimeClasspath", folder)
    }
}
sourceSets["main"].resources.srcDir(appLicences)

/** The SHA-256 of the certificate under [signing]'s alias, as keytool prints it, without the colons. */
fun certificateSha256(signing: Map<String, String>): String {
    val store = KeyStore.getInstance(File(signing.getValue("path")), signing.getValue("storePassword").toCharArray())
    val certificate = checkNotNull(store.getCertificate(signing.getValue("alias"))) { "no certificate under ${signing["alias"]} in ${signing["path"]}" }
    return MessageDigest.getInstance("SHA-256").digest(certificate.encoded).joinToString("") { "%02x".format(it) }
}

compose.desktop {
    application {
        mainClass = "com.aimdi.xtanative.desktop.MainKt"
        // Settings shows it; the Android app reads its own from the package.
        jvmArgs("-Dxtanative.version=$versionName")
        if (releaseTag.isNotEmpty()) jvmArgs("-Dxtanative.release_tag=$releaseTag")
        nativeDistributions {
            packageName = "xta-native"
            packageVersion = versionName
            // Beside the modules Compose always ships: German month names and
            // separators (jdk.localedata), and what the libraries may load.
            modules("jdk.localedata", "jdk.unsupported", "java.naming", "java.management", "java.instrument", "java.sql")
            // The voice engine downloaded voices read with, as XTA's Linux bundle
            // carries it: tool/voice_engine.py puts it in linux-x64/voice-engine
            // here (CI does before it builds), and the app finds it under
            // lib/app/resources. Without it, voices show as unavailable.
            appResourcesRootDir.set(layout.buildDirectory.dir("voice-engine-resources"))
        }
    }
}
